fn dict_for(locale: Locale) -> &'static Dict {
    static FR: OnceLock<Dict> = OnceLock::new();
    static EN: OnceLock<Dict> = OnceLock::new();
    static ES: OnceLock<Dict> = OnceLock::new();
    static DE: OnceLock<Dict> = OnceLock::new();
    match locale {
        Locale::Fr => FR.get_or_init(fr),
        Locale::En => EN.get_or_init(en),
        Locale::Es => ES.get_or_init(es),
        Locale::De => DE.get_or_init(de),
    }
}

pub fn lookup(locale: Locale, key: &'static str) -> String {
    dict_for(locale)
        .get(key)
        .copied()
        .unwrap_or(key)
        .to_string()
}
